package com.l9_anagrams.controller;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import com.l9_anagrams.auth.userdetails.AppUserPrincipal;
import com.l9_anagrams.config.OpenApiConfig;
import com.l9_anagrams.dto.shop.PackOpeningResponseDto;
import com.l9_anagrams.dto.shop.ShopPacksResponseDto;
import com.l9_anagrams.exception.ApiErrorResponse;
import com.l9_anagrams.service.ShopService;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.enums.ParameterIn;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;

/** Negozio (Contratto API §6): pacchetti in vendita, acquisto e apertura, riepilogo di un'apertura. */
@RestController
@RequestMapping("/api/shop")
@Tag(name = "Shop", description = "Card packs on sale, purchase and opening, opening summaries")
@SecurityRequirement(name = OpenApiConfig.BEARER_AUTH)
public class ShopController {

	public static final String IDEMPOTENCY_KEY_HEADER = "Idempotency-Key";

	private final ShopService shopService;

	public ShopController(ShopService shopService) {
		this.shopService = shopService;
	}

	@GetMapping("/packs")
	@Operation(summary = "List packs on sale",
			description = "Return the player's credits, the Sun counter and the active packs with slots, Star odds, "
					+ "guarantees and availability. Prices and contents come from the database.")
	@ApiResponses({
			@ApiResponse(responseCode = "200", description = "Packs on sale", content = @Content(schema = @Schema(implementation = ShopPacksResponseDto.class))),
			@ApiResponse(responseCode = "401", description = "Authentication required", content = @Content(schema = @Schema(implementation = ApiErrorResponse.class))),
			@ApiResponse(responseCode = "404", description = "Player not found for this account", content = @Content(schema = @Schema(implementation = ApiErrorResponse.class)))
	})
	public ResponseEntity<ShopPacksResponseDto> listPacks(@AuthenticationPrincipal AppUserPrincipal user) {
		return ResponseEntity.ok(shopService.listPacks(user.userId()));
	}

	@PostMapping("/packs/{code}/purchase")
	@Operation(summary = "Buy and open a pack",
			description = "Charge the pack price and open it in the same transaction: the cards are added to the collection. "
					+ "The Idempotency-Key header makes the request safe to retry: the same key returns the same opening "
					+ "without charging again. If the purchase fails, credits are not touched.")
	@ApiResponses({
			@ApiResponse(responseCode = "201", description = "Pack bought and opened (also returned when the same Idempotency-Key is retried)", content = @Content(schema = @Schema(implementation = PackOpeningResponseDto.class))),
			@ApiResponse(responseCode = "400", description = "Idempotency-Key missing or longer than 64 characters", content = @Content(schema = @Schema(implementation = ApiErrorResponse.class))),
			@ApiResponse(responseCode = "401", description = "Authentication required", content = @Content(schema = @Schema(implementation = ApiErrorResponse.class))),
			@ApiResponse(responseCode = "404", description = "Pack or player not found", content = @Content(schema = @Schema(implementation = ApiErrorResponse.class))),
			@ApiResponse(responseCode = "409", description = "INSUFFICIENT_CREDITS: not enough credits; LIMIT_REACHED: already opened in this lunar cycle; "
					+ "NOT_YET_RELEASED: the pack is not on sale yet; CONFLICT: the Idempotency-Key was already used for another pack",
					content = @Content(schema = @Schema(implementation = ApiErrorResponse.class)))
	})
	public ResponseEntity<PackOpeningResponseDto> purchase(
			@Parameter(description = "Pack code", example = "COSTELLAZIONE") @PathVariable("code") String code,
			// Non obbligatorio per Spring: l'assenza la segnala il service con 400 VALIDATION_ERROR e un messaggio chiaro
			@Parameter(in = ParameterIn.HEADER, name = IDEMPOTENCY_KEY_HEADER, required = true,
					description = "UUID generated by the client for this purchase and reused on retries (1-64 characters)",
					example = "3f1c2a9e-7b4d-4c2e-9a51-0d8e6f4b2c17")
			@RequestHeader(value = IDEMPOTENCY_KEY_HEADER, required = false) String idempotencyKey,
			@AuthenticationPrincipal AppUserPrincipal user) {
		PackOpeningResponseDto response = shopService.purchase(user.userId(), code, idempotencyKey);
		return ResponseEntity.status(HttpStatus.CREATED).body(response);
	}

	@GetMapping("/openings/{openingId}")
	@Operation(summary = "Get a pack opening",
			description = "Return the summary of one of the player's openings, to recover it if the opening animation was interrupted.")
	@ApiResponses({
			@ApiResponse(responseCode = "200", description = "Opening summary", content = @Content(schema = @Schema(implementation = PackOpeningResponseDto.class))),
			@ApiResponse(responseCode = "401", description = "Authentication required", content = @Content(schema = @Schema(implementation = ApiErrorResponse.class))),
			@ApiResponse(responseCode = "404", description = "Opening not found or owned by another player", content = @Content(schema = @Schema(implementation = ApiErrorResponse.class)))
	})
	public ResponseEntity<PackOpeningResponseDto> getOpening(
			@Parameter(description = "Opening id", example = "501") @PathVariable("openingId") Long openingId,
			@AuthenticationPrincipal AppUserPrincipal user) {
		return ResponseEntity.ok(shopService.getOpening(user.userId(), openingId));
	}
}
